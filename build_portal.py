"""Build the offline portal from the current catalogue without changing the archive."""
import argparse
import json
from pathlib import Path
from urllib.parse import quote
from capture_branding import excluded_regulator_brand

ROOT = Path(__file__).resolve().parent
MARKER = "<!-- CIW offline portal: generated by build_portal.py -->"
ROOT_OUTPUT = ROOT.parent / "ciw-care-home-inspection-portal.html"


def main():
    parser = argparse.ArgumentParser(description="Build the self-contained CareLens Cymru portal.")
    parser.add_argument("--data", type=Path, default=ROOT / "catalogue.json", help="Catalogue JSON to embed.")
    parser.add_argument("--output-dir", type=Path, help="Destination directory for index.html.")
    parser.add_argument("--public", action="store_true", help="Build only in the output directory; never write the local root portal.")
    args = parser.parse_args()
    template = (ROOT / "portal-template.html").read_text(encoding="utf-8")
    leaflet_js = (ROOT / "assets" / "vendor" / "leaflet.js").read_text(encoding="utf-8")
    leaflet_css = (ROOT / "assets" / "vendor" / "leaflet.css").read_text(encoding="utf-8")
    template = template.replace("__LEAFLET_CSS__", leaflet_css)
    template = template.replace("__LEAFLET_JS__", leaflet_js.replace("</script", "<\\/script"))
    mark = ROOT / "assets" / "carelens-mark.svg"
    if mark.exists():
        template = template.replace('<link rel="icon" href="data:,">',
                                    '<link rel="icon" type="image/svg+xml" href="data:image/svg+xml,' +
                                    quote(mark.read_text(encoding="utf-8"), safe="") + '">')
    source = args.data.resolve()
    output_dir = (args.output_dir or (ROOT / "public" if args.public else ROOT)).resolve()
    if source.exists():
        data = json.loads(source.read_text(encoding="utf-8-sig"))
        if not isinstance(data, dict) or not isinstance(data.get("services"), list):
            raise ValueError("catalogue.json must contain a services array.")
        if args.public and not data.get("meta", {}).get("public_release"):
            raise ValueError("Public builds require the contact-minimised public catalogue from prepare_release.py.")
        branding_path = ROOT / "customer-branding.json"
        if not args.public and branding_path.exists():
            branding = json.loads(branding_path.read_text(encoding="utf-8"))
            for service in data["services"]:
                if service["urn"] in branding.get("services", {}):
                    service["branding"] = branding["services"][service["urn"]]
            data["meta"]["branding"] = branding.get("meta", {})
        for service in data["services"]:
            brand = service.get("branding", {})
            if excluded_regulator_brand(brand.get("logo_url"), brand.get("image_alt", "")):
                brand.pop("logo_url", None)
                brand.pop("image_kind", None)
                brand.update(verified=False, logo_status="regulator_logo_excluded")
    else:
        if args.public:
            raise FileNotFoundError(f"Public catalogue not found: {source}")
        data = {
            "meta": {
                "snapshot_date": "2026-11-01", "total": 1046, "processed": 0,
                "complete": False, "build_note": "The catalogue has not been exported yet. Rebuild after collection.",
            },
            "themes": ["Well-being", "Care and Support", "Environment", "Leadership and Management"],
            "topics": [], "services": [],
        }
    if args.public and data.get("meta", {}).get("public_release") is not True:
        raise ValueError("--public requires a release catalogue with meta.public_release=true. Use --data public/catalogue.json after prepare_release.py.")
    if not args.public and ROOT_OUTPUT.exists():
        with ROOT_OUTPUT.open(encoding="utf-8-sig") as existing:
            if MARKER not in existing.read(500):
                raise FileExistsError(f"Refusing to overwrite an unrelated file: {ROOT_OUTPUT}")
    encoded = json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")
    library_source = next((path for path in [
        output_dir / "report-library.json", source.parent / "report-library.json", ROOT / "report-library.json"
    ] if path.is_file()), None)
    library = json.loads(library_source.read_text(encoding="utf-8-sig")) if library_source else {"meta": {}, "reports": []}
    if not isinstance(library, dict) or not isinstance(library.get("reports"), list):
        raise ValueError("report-library.json must contain a reports array.")
    reports_encoded = json.dumps(library, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")
    archive_candidates = [
        ("Full catalogue JSON", "catalogue.json"),
        ("Catalogue SQLite", "catalogue.sqlite"),
        ("Coverage JSON", "coverage.json"),
        ("Corpus validation JSON", "validation.json"),
        ("Data dictionary & methodology", "DATA-DICTIONARY.txt"),
        ("Official guidance archive manifest", "guidance.json"),
        ("Management report library", "report-library.json"),
        ("Public scope & database schema", "PUBLIC-DATA.txt"),
        ("Project guide", "README.txt"),
        ("Archive README", "README.md"),
        ("Archive README", "README.txt"),
        ("Public release & privacy", "PUBLIC-DATA.txt"),
        ("Database schema", "schema.sql"),
        ("Database schema", "database-schema.sql"),
    ]
    archive_links = [(label, name) for label, name in archive_candidates if (output_dir / name).is_file()]
    output_dir.mkdir(parents=True, exist_ok=True)
    outputs = [(output_dir / "index.html", "./")]
    if not args.public:
        outputs.append((ROOT_OUTPUT, "./ciw-care-home-catalogue/"))
    for path, base in outputs:
        html = template.replace("__CIW_BASE__", json.dumps(base))
        html = html.replace("__CARELENS_REPORTS__", reports_encoded)
        html = html.replace("__CIW_ARCHIVE_LINKS__", json.dumps(archive_links)).replace("__CIW_DATA__", encoded)
        if MARKER not in html:
            raise ValueError("Portal template is missing its generated-output ownership marker.")
        temporary = path.with_suffix(".html.build")
        temporary.write_text(html, encoding="utf-8")
        temporary.replace(path)
        print(f"Built {path.name}: {len(data['services'])} services, {path.stat().st_size:,} bytes")
    if not source.exists():
        print("No catalogue.json yet; outputs show an explicit empty coverage state. Run again after export.")


if __name__ == "__main__":
    main()
